export function uid(prefix) {
  return `${prefix}_${Math.random().toString(36).slice(2, 9)}`
}

function daysAgoISO(days, hour = 10) {
  const d = new Date()
  d.setDate(d.getDate() - days)
  d.setHours(hour, 0, 0, 0)
  return d.toISOString()
}

